// خانة اختيار (قائمة منسدلة) بنفس شكل خانات الاستمارة
@OptIn(ExperimentalMaterial3Api::class)
@Composable
fun FormDropdownField(
    label: String,
    value: String,
    options: List<String>,
    onSelect: (String) -> Unit,
    textColor: Color,
    subTextColor: Color,
    borderColor: Color,
    accent: Color,
    modifier: Modifier = Modifier
) {
    var expanded by remember { mutableStateOf(false) }
    Box(modifier = modifier.fillMaxWidth()) {
        OutlinedTextField(
            value = value,
            onValueChange = {},
            readOnly = true,
            singleLine = true,
            label = { Text(label, color = subTextColor) },
            trailingIcon = {
                Icon(imageVector = Icons.Default.ArrowDropDown, contentDescription = null, tint = textColor)
            },
            colors = OutlinedTextFieldDefaults.colors(
                focusedTextColor = textColor,
                unfocusedTextColor = textColor,
                focusedBorderColor = accent,
                unfocusedBorderColor = borderColor,
                focusedLabelColor = accent,
                unfocusedLabelColor = subTextColor
            ),
            modifier = Modifier.fillMaxWidth()
        )
        // طبقة شفافة: الضغط على الخانة كاملة كيفتح اللائحة
        Box(
            modifier = Modifier
                .matchParentSize()
                .clickable { expanded = true }
        )
        DropdownMenu(
            expanded = expanded,
            onDismissRequest = { expanded = false },
            modifier = Modifier.heightIn(max = 320.dp)
        ) {
            options.forEach { option ->
                DropdownMenuItem(
                    text = { Text(option, fontSize = 13.sp, fontWeight = FontWeight.Bold) },
                    onClick = {
                        onSelect(option)
                        expanded = false
                    }
                )
            }
        }
    }
}

@Composable
fun AddScreen(
    isDriver: Boolean,
    isDarkMode: Boolean,
